import { readFile, writeFile } from "node:fs/promises";
const file = name => new URL(name, import.meta.url);
const core = await readFile(file("src/core.cjs"), "utf8");
const entry = await readFile(file("src/plugin.cjs"), "utf8");
const bundledCore = "(() => {\nconst module = {exports: {}};\n" + core + "\nreturn module.exports;\n})()";
await writeFile(file("main.js"), "// Generated by node build.mjs from src/.\n" +
    entry.replace('require("./core.cjs")', () => bundledCore));
